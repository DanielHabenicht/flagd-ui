#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const uiRoot = path.dirname(path.dirname(path.resolve(__filename)));
const repoRoot = path.resolve(uiRoot, '..');
const targetFile = path.join(uiRoot, 'src', 'environments.ts');

const runGit = (args) => {
  const result = spawnSync('git', ['-C', repoRoot, ...args], { encoding: 'utf8' });
  if (result.status !== 0) {
    return null;
  }
  const output = (result.stdout || '').trim();
  return output || null;
};

const envCommit = process.env.FLAGD_UI_GIT_COMMIT;

const gitCommit = envCommit || runGit(['rev-parse', 'HEAD']);
const gitTag = runGit(['describe', '--tags', '--exact-match']);

const rawBackendRoot = process.env.FLAGD_UI_BACKEND_ROOT;
let backendRoot = rawBackendRoot ? rawBackendRoot.trim() : '';
if (!backendRoot || backendRoot.toLowerCase() === 'null') {
  backendRoot = null;
} else {
  backendRoot = backendRoot.replace(/\/+$/, '');
}

const rawBackendType = process.env.FLAGD_UI_BACKEND_TYPE;
let backendType = 'rest';
if (rawBackendType && (rawBackendType === 'rest' || rawBackendType === 'wasm')) {
  backendType = rawBackendType;
}

const tagValue = gitTag ? JSON.stringify(gitTag) : 'null';
const commitValue = gitCommit ? JSON.stringify(gitCommit) : 'null';
const backendValue = backendRoot ? JSON.stringify(backendRoot) : 'null';
const backendTypeValue = JSON.stringify(backendType);

const fileContents = `/* This file is generated by scripts/generate-environments.js. */

export const GIT_TAG: string | null = ${tagValue};
export const GIT_COMMIT_HASH: string | null = ${commitValue};
export const DEFAULT_BACKEND_ROOT: string | null = ${backendValue};
export const BACKEND_TYPE: 'rest' | 'wasm' = ${backendTypeValue} as 'rest' | 'wasm';
`;

fs.mkdirSync(path.dirname(targetFile), { recursive: true });
fs.writeFileSync(targetFile, fileContents, 'utf8');

console.log(`✓ Generated ${path.relative(uiRoot, targetFile)}`);
